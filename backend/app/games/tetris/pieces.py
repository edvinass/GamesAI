"""Tetromino definitions and bag randomizer."""

import random
from typing import Iterator

PIECE_TYPES = ["I", "O", "T", "S", "Z", "J", "L"]

PIECE_COLORS = {
    "I": "#06b6d4",
    "O": "#eab308",
    "T": "#a855f7",
    "S": "#22c55e",
    "Z": "#ef4444",
    "J": "#3b82f6",
    "L": "#f97316",
}

# Each rotation: cell offsets (dx, dy) from piece anchor (top-left of 4×4 box).
PIECE_SHAPES: dict[str, list[list[tuple[int, int]]]] = {
    "I": [
        [(0, 1), (1, 1), (2, 1), (3, 1)],
        [(2, 0), (2, 1), (2, 2), (2, 3)],
        [(0, 2), (1, 2), (2, 2), (3, 2)],
        [(1, 0), (1, 1), (1, 2), (1, 3)],
    ],
    "O": [
        [(1, 0), (2, 0), (1, 1), (2, 1)],
        [(1, 0), (2, 0), (1, 1), (2, 1)],
        [(1, 0), (2, 0), (1, 1), (2, 1)],
        [(1, 0), (2, 0), (1, 1), (2, 1)],
    ],
    "T": [
        [(1, 0), (0, 1), (1, 1), (2, 1)],
        [(1, 0), (1, 1), (2, 1), (1, 2)],
        [(0, 1), (1, 1), (2, 1), (1, 2)],
        [(1, 0), (0, 1), (1, 1), (1, 2)],
    ],
    "S": [
        [(1, 0), (2, 0), (0, 1), (1, 1)],
        [(1, 0), (1, 1), (2, 1), (2, 2)],
        [(1, 1), (2, 1), (0, 2), (1, 2)],
        [(0, 0), (0, 1), (1, 1), (1, 2)],
    ],
    "Z": [
        [(0, 0), (1, 0), (1, 1), (2, 1)],
        [(2, 0), (1, 1), (2, 1), (1, 2)],
        [(0, 1), (1, 1), (1, 2), (2, 2)],
        [(1, 0), (0, 1), (1, 1), (0, 2)],
    ],
    "J": [
        [(0, 0), (0, 1), (1, 1), (2, 1)],
        [(1, 0), (2, 0), (1, 1), (1, 2)],
        [(0, 1), (1, 1), (2, 1), (2, 2)],
        [(1, 0), (1, 1), (0, 2), (1, 2)],
    ],
    "L": [
        [(2, 0), (0, 1), (1, 1), (2, 1)],
        [(1, 0), (1, 1), (1, 2), (2, 2)],
        [(0, 1), (1, 1), (2, 1), (0, 2)],
        [(0, 0), (1, 0), (1, 1), (1, 2)],
    ],
}

SPAWN_X = 3
SPAWN_Y = 0


def piece_cells(piece_type: str, rotation: int, x: int, y: int) -> list[tuple[int, int]]:
    shape = PIECE_SHAPES[piece_type][rotation % 4]
    return [(x + dx, y + dy) for dx, dy in shape]


def new_bag() -> list[str]:
    bag = PIECE_TYPES.copy()
    random.shuffle(bag)
    return bag


def bag_generator() -> Iterator[str]:
    bag: list[str] = []
    while True:
        if not bag:
            bag = new_bag()
        yield bag.pop()
