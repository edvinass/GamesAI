export function pieceCells(
  type: string,
  rotation: number,
  x: number,
  y: number,
): [number, number][] {
  const shape = PIECE_SHAPES[type]?.[rotation % 4] ?? []
  return shape.map(([dx, dy]) => [x + dx, y + dy] as [number, number])
}
